import { readdir, readFile, watch, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const galleryRoot = path.join(projectRoot, "static", "media", "videos");
const manifestPath = path.join(galleryRoot, "gallery.json");
const manifestScriptPath = path.join(galleryRoot, "gallery-data.js");
const categoryFolderPattern = /^--(.+?)--$/u;
const videoExtensionPattern = /\.(?:m4v|mp4|ogg|ogv|webm)$/iu;
const collator = new Intl.Collator("en", { numeric: true, sensitivity: "base" });
const categoryPriority = new Map([
    ["app-promotional-video", 0],
    ["trend-editing", 1],
    ["editing-project", 2]
]);

const categoryIdFromName = (name) => name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/gu, "")
    .toLowerCase()
    .replace(/&/gu, " and ")
    .replace(/[^a-z0-9]+/gu, "-")
    .replace(/^-+|-+$/gu, "");

const labelFromFilename = (filename) => {
    const basename = filename.replace(/\.[^.]+$/u, "");
    return basename
        .replace(/[_-]+/gu, " ")
        .replace(/\s+/gu, " ")
        .trim()
        .replace(/\b\w/gu, (character) => character.toUpperCase());
};

const publicVideoPath = (folder, filename) => [
    "static",
    "media",
    "videos",
    folder,
    filename
].map(encodeURIComponent).join("/");

const buildManifest = async () => {
    const galleryEntries = await readdir(galleryRoot, { withFileTypes: true });
    const categoryFolders = galleryEntries.filter((entry) => entry.isDirectory());
    const invalidFolders = categoryFolders
        .filter((entry) => !categoryFolderPattern.test(entry.name))
        .map((entry) => entry.name);

    if (invalidFolders.length > 0) {
        throw new Error(
            `Invalid category folder name(s): ${invalidFolders.join(", ")}. ` +
            "Use the --Category Name-- pattern."
        );
    }

    const categories = [];
    const categoryIds = new Set();

    for (const folder of categoryFolders.sort((left, right) => collator.compare(left.name, right.name))) {
        const match = folder.name.match(categoryFolderPattern);
        const name = match[1].replace(/\s+/gu, " ").trim();
        const id = categoryIdFromName(name);
        if (!id) throw new Error(`Category folder ${folder.name} does not contain a usable name.`);
        if (categoryIds.has(id)) {
            throw new Error(`Duplicate category id "${id}" generated by folder ${folder.name}.`);
        }
        categoryIds.add(id);

        const folderPath = path.join(galleryRoot, folder.name);
        const videoEntries = (await readdir(folderPath, { withFileTypes: true }))
            .filter((entry) => entry.isFile() && videoExtensionPattern.test(entry.name))
            .sort((left, right) => collator.compare(left.name, right.name));

        if (videoEntries.length === 0) continue;

        categories.push({
            id,
            name,
            folder: folder.name,
            videos: videoEntries.map((video) => ({
                file: video.name,
                src: publicVideoPath(folder.name, video.name),
                title: labelFromFilename(video.name)
            }))
        });
    }

    categories.sort((left, right) => {
        const priorityDifference = (categoryPriority.get(left.id) ?? 100)
            - (categoryPriority.get(right.id) ?? 100);
        return priorityDifference || collator.compare(left.name, right.name);
    });

    return {
        version: 1,
        folderPattern: "--Category Name--",
        videoCount: categories.reduce((total, category) => total + category.videos.length, 0),
        categories
    };
};

const serializeManifest = (manifest) => ({
    json: `${JSON.stringify(manifest, null, 2)}\n`,
    script: `window.VIDEO_GALLERY_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`
});

const generate = async ({ check = false } = {}) => {
    const manifest = await buildManifest();
    const serialized = serializeManifest(manifest);

    if (check) {
        let existingManifest = "";
        let existingManifestScript = "";
        try {
            existingManifest = await readFile(manifestPath, "utf8");
        } catch {
            // A missing manifest is reported by the comparison below.
        }
        try {
            existingManifestScript = await readFile(manifestScriptPath, "utf8");
        } catch {
            // A missing browser data script is reported by the comparison below.
        }

        if (
            existingManifest !== serialized.json ||
            existingManifestScript !== serialized.script
        ) {
            console.error("Video gallery data files are missing or stale. Run:");
            console.error("  node scripts/generate-video-gallery.mjs");
            process.exitCode = 1;
            return;
        }

        console.log(`Video gallery data is current (${manifest.videoCount} videos).`);
        return;
    }

    await Promise.all([
        writeFile(manifestPath, serialized.json, "utf8"),
        writeFile(manifestScriptPath, serialized.script, "utf8")
    ]);
    console.log(`Generated video gallery data with ${manifest.videoCount} videos.`);
};

if (process.argv.includes("--watch")) {
    await generate();
    console.log("Watching video category folders for changes...");

    let regenerationTimer = null;
    for await (const event of watch(galleryRoot, { recursive: true })) {
        if (["gallery.json", "gallery-data.js"].includes(event.filename)) continue;
        clearTimeout(regenerationTimer);
        regenerationTimer = setTimeout(() => {
            void generate().catch((error) => console.error(error.message));
        }, 180);
    }
} else {
    await generate({ check: process.argv.includes("--check") });
}
