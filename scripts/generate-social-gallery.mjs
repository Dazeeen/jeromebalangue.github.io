import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const galleryRoot = path.join(projectRoot, "static", "media", "images", "social-media-designs");
const manifestPath = path.join(galleryRoot, "gallery.json");
const manifestScriptPath = path.join(galleryRoot, "gallery-data.js");
const categoryFolderPattern = /^--(.+?)--$/u;
const imageExtensionPattern = /\.(?:avif|gif|jpe?g|png|svg|webp)$/iu;
const collator = new Intl.Collator("en", { numeric: true, sensitivity: "base" });

const categoryIdFromName = (name) => name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/gu, "")
    .toLowerCase()
    .replace(/&/gu, " and ")
    .replace(/[^a-z0-9]+/gu, "-")
    .replace(/^-+|-+$/gu, "");

const labelFromFilename = (filename) => {
    const basename = filename.replace(/\.[^.]+$/u, "");
    return basename
        .replace(/[_-]+/gu, " ")
        .replace(/\s+/gu, " ")
        .trim()
        .replace(/\b\w/gu, (character) => character.toUpperCase())
        .replace(/\b12kw\b/giu, "12kW");
};

const publicImagePath = (folder, filename) => [
    "static",
    "media",
    "images",
    "social-media-designs",
    folder,
    filename
].map(encodeURIComponent).join("/");

const buildManifest = async () => {
    const galleryEntries = await readdir(galleryRoot, { withFileTypes: true });
    const categoryFolders = galleryEntries.filter((entry) => entry.isDirectory());
    const invalidFolders = categoryFolders
        .filter((entry) => !categoryFolderPattern.test(entry.name))
        .map((entry) => entry.name);

    if (invalidFolders.length > 0) {
        throw new Error(
            `Invalid category folder name(s): ${invalidFolders.join(", ")}. ` +
            "Use the --Category Name-- pattern."
        );
    }

    const categories = [];
    const categoryIds = new Set();

    for (const folder of categoryFolders.sort((left, right) => collator.compare(left.name, right.name))) {
        const match = folder.name.match(categoryFolderPattern);
        const name = match[1].replace(/\s+/gu, " ").trim();
        const id = categoryIdFromName(name);
        if (!id) throw new Error(`Category folder ${folder.name} does not contain a usable name.`);
        if (categoryIds.has(id)) {
            throw new Error(`Duplicate category id "${id}" generated by folder ${folder.name}.`);
        }
        categoryIds.add(id);

        const folderPath = path.join(galleryRoot, folder.name);
        const imageEntries = (await readdir(folderPath, { withFileTypes: true }))
            .filter((entry) => entry.isFile() && imageExtensionPattern.test(entry.name))
            .sort((left, right) => collator.compare(left.name, right.name));

        if (imageEntries.length === 0) continue;

        categories.push({
            id,
            name,
            folder: folder.name,
            images: imageEntries.map((image) => ({
                file: image.name,
                src: publicImagePath(folder.name, image.name),
                alt: labelFromFilename(image.name)
            }))
        });
    }

    return {
        version: 1,
        folderPattern: "--Category Name--",
        imageCount: categories.reduce((total, category) => total + category.images.length, 0),
        categories
    };
};

const manifest = await buildManifest();
const serializedManifest = `${JSON.stringify(manifest, null, 2)}\n`;
const serializedManifestScript = `window.SOCIAL_GALLERY_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;

if (process.argv.includes("--check")) {
    let existingManifest = "";
    let existingManifestScript = "";
    try {
        existingManifest = await readFile(manifestPath, "utf8");
    } catch {
        // A missing manifest is reported by the comparison below.
    }
    try {
        existingManifestScript = await readFile(manifestScriptPath, "utf8");
    } catch {
        // A missing browser data script is reported by the comparison below.
    }

    if (
        existingManifest !== serializedManifest ||
        existingManifestScript !== serializedManifestScript
    ) {
        console.error("Social gallery data files are missing or stale. Run:");
        console.error("  node scripts/generate-social-gallery.mjs");
        process.exitCode = 1;
    } else {
        console.log(`Social gallery data is current (${manifest.imageCount} images).`);
    }
} else {
    await Promise.all([
        writeFile(manifestPath, serializedManifest, "utf8"),
        writeFile(manifestScriptPath, serializedManifestScript, "utf8")
    ]);
    console.log(`Generated social gallery data with ${manifest.imageCount} images.`);
}
